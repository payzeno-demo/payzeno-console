/**
 * `InvoiceDetailPage` — child route of `InvoicesPage`.
 *
 * Still on the legacy path: `useLegacyQuery` straight onto `GET /v1/invoices/:invoiceId`. The
 * line items come from payzeno-billing-legacy's JPA model verbatim, which is why they are a
 * plain array on the invoice rather than a paginated sub-resource.
 *
 * Voiding an invoice is admin-only and, because nothing here participates in invalidation,
 * refetches by hand.
 */
import { useState } from 'react';
import { useParams } from 'react-router-dom';

import type { Invoice } from '@payzeno/contracts';

import { ErrorState } from '@components/feedback/ErrorState';
import { LoadingPage } from '@components/feedback/LoadingPage';
import { NotFound } from '@components/feedback/NotFound';
import { PageContainer } from '@components/layout/PageContainer';
import { PageHeader } from '@components/layout/PageHeader';
import { Alert } from '@components/ui/Alert';
import { Button } from '@components/ui/Button';
import { Card } from '@components/ui/Card';
import { DateCell } from '@components/data/DateCell';
import { StatusPill } from '@components/data/StatusPill';
import { useLegacyQuery } from '@api/legacy/legacy-query';
import { legacyStatus } from '@api/legacy/legacy-errors';
import { useDocumentTitle } from '@hooks/useDocumentTitle';
import { usePermissions } from '@hooks/usePermissions';
// TODO(rrefactor): MoneyCell — same JPY bug as invoices.columns.tsx. PAY-1968.
import { formatAmount, formatCount, humanise } from '@lib/format';

import { voidInvoice } from './invoices.queries';

export function InvoiceDetailPage() {
  const { invoiceId = '' } = useParams<{ invoiceId: string }>();
  useDocumentTitle(invoiceId ? `Invoice ${invoiceId}` : 'Invoice');

  const { can } = usePermissions();
  const [voidError, setVoidError] = useState<string | null>(null);
  const { data, isLoading, error, refetch } = useLegacyQuery<Invoice>(
    `/invoices/${encodeURIComponent(invoiceId)}`,
    { enabled: invoiceId.length > 0 },
  );

  if (legacyStatus(error) === 404) {
    return <NotFound title="No such invoice" body="It may belong to another account." />;
  }
  if (error) {
    return <ErrorState error={error} title="We could not load this invoice" />;
  }
  if (isLoading || !data) {
    return <LoadingPage label="Loading invoice" />;
  }

  const outstanding = Math.max(0, data.total_minor - data.amount_paid_minor);
  const canVoid = can('settings:write') && (data.status === 'draft' || data.status === 'open');

  const handleVoid = () => {
    setIsVoiding(true);
    setVoidError(null);
    voidInvoice(data.id)
      .then(() => refetch())
      .catch((err: unknown) => {
        setVoidError(err instanceof Error ? err.message : 'The invoice could not be voided.');
      })
      .finally(() => setIsVoiding(false));
  };

  return (
    <PageContainer as="main">
      <PageHeader
        title={`Invoice ${data.number}`}
        description={
          data.migrated_to_ledger ? 'Generated by the ledger' : 'Generated by billing (legacy)'
        }
      >
        <StatusPill status={data.status} label={humanise(data.status)} />
        {canVoid ? (
          <Button type="button" variant="secondary" disabled={isVoiding} onClick={handleVoid}>
            {isVoiding ? 'Voiding…' : 'Void invoice'}
          </Button>
        ) : null}
      </PageHeader>

      {voidError ? (
        <Alert tone="critical" title="Void failed">
          {voidError}
        </Alert>
      ) : null}

      <Card as="section" aria-label="Invoice summary">
        <dl>
          <dt>Period</dt>
          <dd>
            <DateCell value={data.period_start} precision="day" /> —{' '}
            <DateCell value={data.period_end} precision="day" />
          </dd>

          <dt>Subtotal</dt>
          <dd>{formatAmount(data.subtotal_minor, data.currency)}</dd>

          <dt>Tax</dt>
          <dd>{formatAmount(data.tax_minor, data.currency)}</dd>

          <dt>Total</dt>
          <dd>{formatAmount(data.total_minor, data.currency)}</dd>

          <dt>Paid</dt>
          <dd>{formatAmount(data.amount_paid_minor, data.currency)}</dd>

          <dt>Outstanding</dt>
          <dd>{formatAmount(outstanding, data.currency)}</dd>

          <dt>Due</dt>
          <dd>
            <DateCell value={data.due_at} precision="day" />
          </dd>
        </dl>
      </Card>

      <Card as="section" aria-label="Invoice line items">
        <table>
          <caption>Line items on invoice {data.number}</caption>
          <thead>
            <tr>
              <th scope="col">Description</th>
              <th scope="col">Quantity</th>
              <th scope="col">Unit</th>
              <th scope="col">Amount</th>
            </tr>
          </thead>
          <tbody>
            {data.lines.map((line, index) => (
              <tr key={`${line.description}-${index}`}>
                <td>{line.description}</td>
                <td>{formatCount(line.quantity)}</td>
                <td>{formatAmount(line.unit_amount_minor, data.currency)}</td>
                <td>{formatAmount(line.amount_minor, data.currency)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </Card>
    </PageContainer>
  );
}
