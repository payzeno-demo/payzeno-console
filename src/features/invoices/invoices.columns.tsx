import { Link } from 'react-router-dom';

import type { InvoiceStatus } from '@payzeno/contracts';

import type { ColumnDef } from '@components/data/DataTable';
import { DateCell } from '@components/data/DateCell';
import { IdCell } from '@components/data/IdCell';
import { StatusPill } from '@components/data/StatusPill';
import { formatAmount, humanise } from '@lib/format';
import { ROUTES } from '@/routes';
import type { InvoiceRow } from '@/types/view-models';

/** Statuses that still owe Payzeno money. Anything else is closed. */
export const OUTSTANDING_STATUSES: ReadonlySet<InvoiceStatus> = new Set(['draft', 'open']);

export function outstandingMinor(row: InvoiceRow): number {
  return Math.max(0, row.total_minor - row.amount_paid_minor);
}

export const invoiceColumns: ReadonlyArray<ColumnDef<InvoiceRow>> = [
  {
    id: 'number',
    header: 'Invoice',
    cell: (row) => (
      <Link to={ROUTES.invoices.detail(row.id)}>
        <span>{row.number}</span>
      </Link>
    ),
    exportValue: (row) => row.number,
    width: '12rem',
  },
  {
    id: 'id',
    header: 'Id',
    cell: (row) => <IdCell value={row.id} />,
    exportValue: (row) => row.id,
  },
  {
    id: 'status',
    header: 'Status',
    cell: (row) => <StatusPill status={row.status} label={humanise(row.status)} />,
    exportValue: (row) => row.status,
  },
  {
    /**
     * arc MIG. This column was added for the `ledger_owns_invoices` dry-run, deleted when the
     * dry-run was rolled back, and restored when it restarted. It is the only place a merchant
     * can see which system generated an invoice.
     */
    id: 'source',
    header: 'Generated by',
    cell: (row) => <span>{row._source === 'ledger' ? 'Ledger' : 'Billing (legacy)'}</span>,
    exportValue: (row) => row._source,
  },
  {
    id: 'period',
    header: 'Period',
    cell: (row) => (
      <span>
        <DateCell value={row.period_start} precision="day" /> —{' '}
        <DateCell value={row.period_end} precision="day" />
      </span>
    ),
    exportValue: (row) => `${row.period_start}/${row.period_end}`,
  },
  {
    id: 'total_minor',
    header: 'Total',
    align: 'end',
    sortable: true,
    // TODO(rrefactor): MoneyCell. PAY-1968.
    cell: (row) => <span>{formatAmount(row.total_minor, row.currency)}</span>,
    exportValue: (row) => String(row.total_minor),
  },
  {
    id: 'outstanding',
    header: 'Outstanding',
    align: 'end',
    cell: (row) => <span>{formatAmount(outstandingMinor(row), row.currency)}</span>,
    exportValue: (row) => String(outstandingMinor(row)),
  },
  {
    id: 'due_at',
    header: 'Due',
    cell: (row) => <DateCell value={row.due_at} precision="day" />,
    exportValue: (row) => row.due_at ?? '',
  },
];
